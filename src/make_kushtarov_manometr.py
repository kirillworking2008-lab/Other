def set_text(par, text):
    """Заменить текст абзаца, сохранив форматирование первого прогона."""
    runs = par.runs
    if not runs:
        par.add_run(text)
        return
    runs[0].text = text
    for r in runs[1:]:
        r.text = ""


def set_toc(par, title):
    """Строка содержания: заголовок + табуляция + номер страницы (как было)."""
    runs = par.runs
    m = re.search(r"\t(\d+)\s*$", par.text)
    page = m.group(1) if m else ""
    if not runs:
        par.add_run(title + "\t" + page)
        return
    runs[0].text = title
    if len(runs) > 1:
        runs[1].text = "\t" + page
    for r in runs[2:]:
        r.text = ""


def replace_image(doc, index, path):
    """Подменить картинку, сохранив её размеры (кадрируем по пропорции)."""
    shape = doc.inline_shapes[index]
    blip_fill = shape._inline.graphic.graphicData.pic.blipFill
    # в рамке исходника может остаться прямоугольник кадрирования — он режет новую картинку
    for src_rect in blip_fill.findall(qn("a:srcRect")):
        blip_fill.remove(src_rect)
    rid = blip_fill.blip.get(qn("r:embed"))
    part = doc.part.related_parts[rid]
    ratio = shape.width / shape.height
    im = Image.open(path)
    w, h = im.size
    if w / h > ratio:
        nw = int(h * ratio)
        im = im.crop(((w - nw) // 2, 0, (w - nw) // 2 + nw, h))
    else:
        nh = int(w / ratio)
        im = im.crop((0, (h - nh) // 2, w, (h - nh) // 2 + nh))
    buf = io.BytesIO()
    im.convert("RGB").save(buf, "JPEG", quality=90, optimize=True, progressive=True)
    part._blob = buf.getvalue()


def main():
    doc = Document(SRC)
    ps = doc.paragraphs
    assert len(ps) == 156, len(ps)

    toc_idx = {52, 53, 54, 55, 56, 57, 58, 59, 60}
    for idx, text in sorted(TEXT.items()):
        if "graphicData" in ps[idx]._p.xml:      # абзац с рисунком не трогаем
            continue
        if idx in toc_idx:
            set_toc(ps[idx], text)
        else:
            set_text(ps[idx], text)

    # таблицы
    for table, rows in zip(doc.tables, TABLES):
        for row, values in zip(table.rows, rows):
            for cell, value in zip(row.cells, values):
                par = cell.paragraphs[0]
                if par.runs:
                    set_text(par, value)
                else:
                    par.add_run(value)

    # рисунки под новую тему
    for idx, path in IMAGE_REPL.items():
        replace_image(doc, idx, path)

    # список литературы: 8 пунктов исходника
    src_pars = [p for p in doc.paragraphs[148:] if p.text.strip()]
    assert len(src_pars) == 8, len(src_pars)
    for par, text in zip(src_pars, LIT):
        set_text(par, text)

    # название работы в штампе
    W = "{http://schemas.openxmlformats.org/wordprocessingml/2006/main}"
    for part in doc.part.package.parts:
        if not str(part.partname).startswith("/word/header"):
            continue
        for t in part.element.iter(W + "t"):
            if not t.text:
                continue
            for old, new in HEADER_REPL:
                if t.text == old:
                    t.text = new
                    break

    # «Листов» в штампе — фактическое число листов документа
    for part in doc.part.package.parts:
        if not str(part.partname).startswith("/word/header"):
            continue
        ts = list(part.element.iter(W + "t"))
        for k, t in enumerate(ts[:-1]):
            if t.text and t.text.strip() == "Листов":
                nxt = ts[k + 1]
                if nxt.text and nxt.text.strip().isdigit():
                    nxt.text = "13"

    # штамп: номер листа перестаёт «застывать» (поле в группе фигур Word не считает),
    # подписи «Изм.», «Лист», «Подпись» выравниваются по своим ячейкам
    rebuild_page_number(doc)
    add_footer_page_number(doc)

    doc.save(OUT)
    data = open(OUT, "rb").read()
    print("сохранено:", OUT, len(data), "байт, md5", hashlib.md5(data).hexdigest())


if __name__ == "__main__":
    main()
