# ---------------------------------------------------------------- утилиты
def set_text(par, text):
    runs = par.runs
    if not runs:
        par.add_run(text)
        return
    runs[0].text = text
    for r in runs[1:]:
        r.text = ""


def set_toc(par, title):
    runs = par.runs
    m = re.search(r"\t(\d+)\s*$", par.text)
    page = m.group(1) if m else ""
    if not runs:
        par.add_run(title + "\t" + page)
        return
    runs[0].text = title
    if len(runs) > 1:
        runs[1].text = "\t" + page
    for r in runs[2:]:
        r.text = ""


def replace_image(doc, index, path):
    """Подменить картинку без кадрирования: высота рамки сохраняется,
    ширина подгоняется под пропорции снимка."""
    shape = doc.inline_shapes[index]
    blip_fill = shape._inline.graphic.graphicData.pic.blipFill
    for src_rect in blip_fill.findall(qn("a:srcRect")):
        blip_fill.remove(src_rect)

    rid = blip_fill.blip.get(qn("r:embed"))
    part = doc.part.related_parts[rid]

    im = Image.open(path).convert("RGB")
    w, h = im.size
    width_emu = int(shape.height * w / h)
    shape.width = Emu(width_emu)

    # мелкие штриховые рисунки растягиваем до ~200 dpi, чтобы линии не «мылились»
    need = int(width_emu / 914400 * 200)
    if w < need:
        k = need / w
        im = im.resize((need, int(round(h * k))), Image.LANCZOS)

    buf = __import__("io").BytesIO()
    im.save(buf, "JPEG", quality=92, optimize=True, progressive=True)
    part._blob = buf.getvalue()


def fix_content_types(path):
    """В исходном файле тип картинок объявлен как image/jpg — нестандартно:
    Word и сторонние просмотрщики такие рисунки могут не показать."""
    import shutil
    import zipfile

    tmp = path + ".tmp"
    with zipfile.ZipFile(path) as zin, zipfile.ZipFile(tmp, "w", zipfile.ZIP_DEFLATED) as zout:
        for item in zin.infolist():
            data = zin.read(item.filename)
            if item.filename == "[Content_Types].xml":
                text = data.decode("utf-8")
                text = text.replace('ContentType="image/jpg"', 'ContentType="image/jpeg"')
                data = text.encode("utf-8")
            zout.writestr(item, data)
    shutil.move(tmp, path)


def main():
    doc = Document(SRC)
    ps = doc.paragraphs
    assert len(ps) == 156, len(ps)

    toc_idx = {52, 53, 54, 55, 56, 57, 58, 59, 60}
    for idx, text in sorted(TEXT.items()):
        if "graphicData" in ps[idx]._p.xml:
            continue
        if idx in toc_idx:
            set_toc(ps[idx], text)
        else:
            set_text(ps[idx], text)

    for table, rows in zip(doc.tables, TABLES):
        for row, values in zip(table.rows, rows):
            for cell, value in zip(row.cells, values):
                par = cell.paragraphs[0]
                if par.runs:
                    set_text(par, value)
                else:
                    par.add_run(value)

    for idx, path in IMAGE_REPL.items():
        replace_image(doc, idx, path)

    src_pars = [p for p in doc.paragraphs[148:] if p.text.strip()]
    assert len(src_pars) == 8, len(src_pars)
    for par, text in zip(src_pars, LIT):
        set_text(par, text)

    doc.save(OUT)
    fix_content_types(OUT)
    data = open(OUT, "rb").read()
    print("сохранено:", OUT, len(data), "байт, md5", hashlib.md5(data).hexdigest())


if __name__ == "__main__":
    main()
