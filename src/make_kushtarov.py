def replace_image(doc, index, path):
    """Подменить картинку, сохранив её размеры в документе (кадрируем по пропорции)."""
    shape = doc.inline_shapes[index]
    rid = shape._inline.graphic.graphicData.pic.blipFill.blip.get(qn("r:embed"))
    part = doc.part.related_parts[rid]
    ratio = shape.width / shape.height
    im = Image.open(path)
    w, h = im.size
    if w / h > ratio:
        nw = int(h * ratio)
        im = im.crop(((w - nw) // 2, 0, (w - nw) // 2 + nw, h))
    else:
        nh = int(w / ratio)
        im = im.crop((0, (h - nh) // 2, w, (h - nh) // 2 + nh))
    buf = io.BytesIO()
    im.convert("RGB").save(buf, "JPEG", quality=92)
    part._blob = buf.getvalue()


