# ---------------------------------------------------------------- утилиты
def set_text(par, text):
    """Заменить текст абзаца, сохранив форматирование первого прогона."""
    runs = par.runs
    if not runs:
        par.add_run(text)
        return
    runs[0].text = text
    for r in runs[1:]:
        r.text = ""


def set_toc(par, title):
    """Строка содержания: заголовок + табуляция + номер страницы (как было)."""
    runs = par.runs
    old = par.text
    m = re.search(r"\t(\d+)\s*$", old)
    page = m.group(1) if m else ""
    runs[0].text = title
    if len(runs) > 1:
        runs[1].text = "\t" + page
    for r in runs[2:]:
        r.text = ""


def main():
    doc = Document(SRC)
    ps = doc.paragraphs

    for idx, text in sorted(TEXT.items()):
        if idx in (52, 53, 54, 55, 56, 57, 58, 59, 60):
            set_toc(ps[idx], text)
        else:
            set_text(ps[idx], text)

    # таблицы
    for table, rows in zip(doc.tables, TABLES):
        for row, values in zip(table.rows, rows):
            for cell, value in zip(row.cells, values):
                par = cell.paragraphs[0]
                if par.runs:
                    set_text(par, value)
                else:
                    par.add_run(value)

    # рисунок 1 — под тему
    for idx, path in IMAGE_REPL.items():
        replace_image(doc, idx, path)

    # штамп в колонтитулах
    for name in doc.part.package.parts:
        partname = str(name.partname)
        if not partname.startswith("/word/header"):
            continue
        element = name.element
        for t in element.iter("{http://schemas.openxmlformats.org/wordprocessingml/2006/main}t"):
            if not t.text:
                continue
            for old, new in HEADER_REPL:
                if t.text == old or old in t.text:
                    t.text = t.text.replace(old, new)
                    break

    doc.save(OUT)
    print("сохранено:", OUT, os.path.getsize(OUT), "байт")


if __name__ == "__main__":
    main()
